#!/usr/bin/env python3
"""Разовий скрипт виведення розкладу суші GEO_LAYOUT з картини світу.

Позафазна лінія «візуальні порівняння», кандидат А «нічний супутник»
(Work-сесія 2026-10-21, виконано 2026-10-22; скориговано за фідбеком
власника 2026-10-23: острів під радаром, радар по центру клітинки).

Джерело: assets-src/geo-map2.jpg (1024x768, сирець власника, поза git).
Ассет рантайму: assets/geo-map.webp — нативний кроп вікна
(WX0..WX0+768, WY0..WY0+432 => 768x432, 1:1 з канвою 768x432).
Вікно вибрано так, щоб ЯСКРАВИЙ острів з вогнями сирця
(x 496..544, y 512..584) стояв рівно під клітинкою бази (8,4):
клітинка (8,4) = сирець x 112+8*48..112+9*48, y 334+4*48..334+5*48.

Правило класифікації (доручення Work): клітинка 16x9 = суша, якщо медіана
яскравості її 48x48-піксельної ділянки вікна вище порогу.
Поріг за фактичним джерелом: 17.4 — центр розриву у розподілі медіан
клітинок (океан плоско 12.0-13.8; острів бази 19.2; розрив 15.7 -> 19.1).

Жорсткі перевірки доручення (невиконання = стоп, поріг не силувати):
  (а) клітинка бази (8,4) — суша;
  (б) суша не торкається лівого/правого краю карти (без швів зшивання).
Орієнтир суші ~30-40% поступається вимозі власника «острів під радаром»
(фідбек 2026-10-23): вікно повернуте до архіпелагу, суша ~8/144 (5.6%).

Результат комітується константою GEO_LAYOUT у src/core/render-core.ts;
рантайм від ассета і цього скрипта НЕ залежить (розклад — константа).

Запуск: python3 scripts/geo-layout.py  (з кореня репо; залежність: Pillow)
"""

from PIL import Image
import numpy as np

SRC = 'assets-src/geo-map2.jpg'
WX0, WY0 = 112, 334  # вікно кропу в координатах сирця (острів під (8,4))
TH = 17.4  # поріг за фактичним джерелом (див. docstring)

im = Image.open(SRC).convert('RGB')
a = np.asarray(im).astype(float)
lum = 0.2126 * a[:, :, 0] + 0.7152 * a[:, :, 1] + 0.0722 * a[:, :, 2]
H, W = lum.shape
win_h, win_w = 432, 768  # 9*48 x 16*48 — 1:1 з канвою

med = np.zeros((9, 16))
for gy in range(9):
    for gx in range(16):
        win = lum[WY0 + gy * 48:WY0 + (gy + 1) * 48, WX0 + gx * 48:WX0 + (gx + 1) * 48]
        med[gy, gx] = np.median(win)

land = med > TH
base_ok = bool(land[4, 8])
edges_ok = not land[:, 0].any() and not land[:, 15].any()
frac = land.mean() * 100

rows = []
for gy in range(9):
    rows.append(''.join('B' if (gx, gy) == (8, 4) else 'L' if land[gy, gx] else '.' for gx in range(16)))

print('джерело %dx%d, вікно x %d..%d, y %d..%d, поріг %.1f' % (W, H, WX0, WX0 + win_w, WY0, WY0 + win_h, TH))
print('медіана клітинки бази (8,4): %.2f' % med[4, 8])
print(' суша: %d/144 (%.1f%%)' % (land.sum(), frac))
print(' (а) база (8,4) — суша: %s' % ('OK' if base_ok else 'FAIL'))
print(' (б) краї X — океан:     %s' % ('OK' if edges_ok else 'FAIL'))
print('GEO_LAYOUT:')
for r in rows:
    print("  '%s'," % r)
assert base_ok and edges_ok, 'жорсткі перевірки не пройдено — стоп'
