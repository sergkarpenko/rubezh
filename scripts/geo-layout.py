#!/usr/bin/env python3
"""Разовий скрипт виведення розкладу суші GEO_LAYOUT з картини світу.

Позафазна лінія «візуальні порівняння», кандидат А «нічний супутник»
(Work-сесія 2026-10-21, виконано 2026-10-22; скориговано за фідбеком
власника 2026-10-23 x4: острів під радаром; вище; масштаб мельче;
вказівка «сюди» — клітинка бази на яскравому мисі-«острові»
південного узбережжя материка).

Джерело: assets-src/geo-map2.jpg (1024x768, сирець власника, поза git).
Ассет рантайму: assets/geo-map.webp — вікно сирця x 0..1024, y 9..639
(повна ширина, 82% висоти — увесь материк з вогнями) + безшовні
паддінги тоном темної рамки сирця: захід 68px, схід 28px;
1120x630 (16:9), 1:1 з вікном.
Клітинка бази (8,4) = сирець x 492..562, y 289..359 — ЯСКРАВИЙ
мис-«острів» південного узбережжя материка (сирець x 480..576,
y 288..352, піки 40-61, яскраве ядро покриває клітинку ~90%).

Правило класифікації (доручення Work): клітинка 16x9 = суша, якщо
медіана яскравості її 70x70-піксельної ділянки вікна вище порогу
(ділянки за межами сирця — паддінг ~9, океан).
Поріг за фактичним джерелом: 16.5 — центр розриву океан→суша у
розподілі медіан (океан плоско 12.8-13.8; розрив 15.0 -> 18.0;
медіана клітинки бази 35.6).

Жорсткі перевірки доручення (виконані БЕЗ відхилень):
  (а) клітинка бази (8,4) — суша (медіана 35.6);
  (б) суша не торкається лівого/правого краю карти (без швів
      зшивання): захід — паддінг/темна рамка, схід — рамка+паддінг.
Орієнтир суші 30-40% — виконано: 46/144 (31.9%).

Результат комітується константою GEO_LAYOUT у src/core/render-core.ts;
рантайм від ассета і цього скрипта НЕ залежить (розклад — константа).

Запуск: python3 scripts/geo-layout.py  (з кореня репо; залежність: Pillow)
"""

from PIL import Image
import numpy as np

SRC = 'assets-src/geo-map2.jpg'
WX0, WY0, CELL = -68, 9, 70  # вікно кропу (захід — паддінг рамки); клітинка 70×70
TH = 16.5  # поріг за фактичним джерелом (див. docstring)
PAD_VAL = 9.0  # тон темної рамки сирця (західний/східний паддінг — океан)

im = Image.open(SRC).convert('RGB')
a = np.asarray(im).astype(float)
lum = 0.2126 * a[:, :, 0] + 0.7152 * a[:, :, 1] + 0.0722 * a[:, :, 2]
H, W = lum.shape

med = np.zeros((9, 16))
for gy in range(9):
    for gx in range(16):
        y1, y2 = WY0 + gy * CELL, WY0 + (gy + 1) * CELL
        x1, x2 = WX0 + gx * CELL, WX0 + (gx + 1) * CELL
        cell = np.full((CELL, CELL), PAD_VAL)  # паддінг за межами сирця
        ys, ye = max(y1, 0), min(y2, H)
        xs, xe = max(x1, 0), min(x2, W)
        if ys < ye and xs < xe:
            cell[ys - y1:ye - y1, xs - x1:xe - x1] = lum[ys:ye, xs:xe]
        med[gy, gx] = np.median(cell)

land = med > TH
base_ok = bool(land[4, 8])
edges_ok = not land[:, 0].any() and not land[:, 15].any()
frac = land.mean() * 100

rows = []
for gy in range(9):
    rows.append(''.join('B' if (gx, gy) == (8, 4) else 'L' if land[gy, gx] else '.' for gx in range(16)))

print('джерело %dx%d, вікно x %d..%d, y %d..%d (плюс паддінги рамки), клітинка %d, поріг %.1f'
      % (W, H, WX0, WX0 + 16 * CELL, WY0, WY0 + 9 * CELL, CELL, TH))
print('медіана клітинки бази (8,4): %.2f' % med[4, 8])
print(' суша: %d/144 (%.1f%%)' % (land.sum(), frac))
print(' (а) база (8,4) — суша: %s' % ('OK' if base_ok else 'FAIL'))
print(' (б) краї X — океан:     %s' % ('OK' if edges_ok else 'FAIL'))
print('GEO_LAYOUT:')
for r in rows:
    print("  '%s'," % r)
assert base_ok and edges_ok, 'жорсткі перевірки не пройдено — стоп'
