#!/usr/bin/env python3
"""Разовий скрипт виведення розкладу суші GEO_LAYOUT з картини світу.

Позафазна лінія «візуальні порівняння», кандидат А «нічний супутник»
(Work-сесія 2026-10-21, виконано 2026-10-22; скориговано за фідбеком
власника 2026-10-23 x2: острів під радаром, радар по центру клітинки;
острів ВИЩЕ, ближче до материка).

Джерело: assets-src/geo-map2.jpg (1024x768, сирець власника, поза git).
Ассет рантайму: assets/geo-map.webp — нативний кроп вікна
(WX0..WX0+768, WY0..WY0+432 => 768x432, 1:1 з канвою 768x432).
Вікно вибрано так, щоб ЯСКРАВИЙ острів з вогнями сирця — найвищий
острів архіпелагу, одразу за південним узбережжям материка — стояв
рівно під клітинкою бази (8,4): острів (сирець x 616..668, y 452..488,
піки 84-92), клітинка (8,4) = сирець x 236+8*48..236+9*48,
y 257+4*48..257+5*48.

Правило класифікації (доручення Work): клітинка 16x9 = суша, якщо медіана
яскравості її 48x48-піксельної ділянки вікна вище порогу.
Поріг за фактичним джерелом: 15.9 — центр розриву океан→суша у розподілі
медіан клітинок (океан плоско 12.8-13.0; острів бази 19.7;
розрив 15.0 -> 16.8).

Жорсткі перевірки доручення (невиконання = стоп, поріг не силувати):
  (а) клітинка бази (8,4) — суша;
  (б) суша не торкається краю карти (без швів зшивання) — для СХІДНОГО
      краю. ВІДХИЛЕННЯ за фідбеком власника 2026-10-23 («острів вище,
      ближче до материка»): західний край — обрізаний материк (суша в
      стовпці 0, рядки 0-1); розв'язку, що одночасно тримає обидва краї
      океаном і ставить північний острів під (8,4), не існує.
Суша ~27/144 (18.8%): материк + острів бази + архіпелаг.

Результат комітується константою GEO_LAYOUT у src/core/render-core.ts;
рантайм від ассета і цього скрипта НЕ залежить (розклад — константа).

Запуск: python3 scripts/geo-layout.py  (з кореня репо; залежність: Pillow)
"""

from PIL import Image
import numpy as np

SRC = 'assets-src/geo-map2.jpg'
WX0, WY0 = 236, 257  # вікно кропу в координатах сирця (острів під (8,4))
TH = 15.9  # поріг за фактичним джерелом (див. docstring)

im = Image.open(SRC).convert('RGB')
a = np.asarray(im).astype(float)
lum = 0.2126 * a[:, :, 0] + 0.7152 * a[:, :, 1] + 0.0722 * a[:, :, 2]
H, W = lum.shape
win_h, win_w = 432, 768  # 9*48 x 16*48 — 1:1 з канвою

med = np.zeros((9, 16))
for gy in range(9):
    for gx in range(16):
        win = lum[WY0 + gy * 48:WY0 + (gy + 1) * 48, WX0 + gx * 48:WX0 + (gx + 1) * 48]
        med[gy, gx] = np.median(win)

land = med > TH
base_ok = bool(land[4, 8])
east_ok = not land[:, 15].any()
west_cut = bool(land[0, 0] or land[1, 0])  # документоване відхилення (фідбек власника)
frac = land.mean() * 100

rows = []
for gy in range(9):
    rows.append(''.join('B' if (gx, gy) == (8, 4) else 'L' if land[gy, gx] else '.' for gx in range(16)))

print('джерело %dx%d, вікно x %d..%d, y %d..%d, поріг %.1f' % (W, H, WX0, WX0 + win_w, WY0, WY0 + win_h, TH))
print('медіана клітинки бази (8,4): %.2f' % med[4, 8])
print(' суша: %d/144 (%.1f%%)' % (land.sum(), frac))
print(' (а) база (8,4) — суша: %s' % ('OK' if base_ok else 'FAIL'))
print(' (б) східний край — океан: %s' % ('OK' if east_ok else 'FAIL'))
print('     західний край — обрізаний материк (відхилення за фідбеком): %s' % ('OK' if west_cut else 'нема'))
print('GEO_LAYOUT:')
for r in rows:
    print("  '%s'," % r)
assert base_ok and east_ok, 'жорсткі перевірки не пройдено — стоп'
