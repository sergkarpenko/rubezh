#!/usr/bin/env python3
"""Разовий скрипт виведення розкладу суші GEO_LAYOUT з картини світу.

Позафазна лінія «візуальні порівняння», кандидат А «нічний супутник»
(Work-сесія 2026-10-21, виконано 2026-10-22; скориговано за фідбеком
власника 2026-10-23 x3: острів під радаром; острів ВИЩЕ, ближче до
материка; масштаб мельче — видно максимум картинки).

Джерело: assets-src/geo-map2.jpg (1024x768, сирець власника, поза git).
Ассет рантайму: assets/geo-map.webp — вікно сирця x 49..1024,
y 158..768 (95% ширини, 79% висоти — максимум, при якому найвищий
острів архіпелагу стоїть під клітинкою бази) + безшовні паддінги:
схід 145px тоном темної рамки сирця, південь 20px дзеркалом океану;
1120x630 (16:9), 1:1 з вікном.
Острів бази: найвищий острів архіпелагу, одразу за південним
узбережжям материка (сирець x 616..668, y 452..488, піки 84..107);
клітинка (8,4) = сирець x 49+8*70..49+9*70, y 158+4*70..158+5*70.

Правило класифікації (доручення Work): клітинка 16x9 = суша, якщо
медіана яскравості її 70x70-піксельної ділянки вікна вище порогу.
Поріг за фактичним джерелом: 17.0 — центр розриву океан→суша у
розподілі медіан (океан плоско 12.8-13.8; розрив 15.8 -> 18.2).

Жорсткі перевірки доручення:
  (а) клітинка бази (8,4) — суша. ВІДХИЛЕННЯ правила виведення (фідбек
      власника 2026-10-23, «масштаб мельче»): острів бази (52x36 px)
      ДРІБНІШИЙ за клітинку 70x70 — медіана клітинки 13.0 (океан-мода);
      поріг НЕ силувався — клітинка бази позначається B (суша за
      призначенням: картина показує острів під радаром).
  (б) суша не торкається лівого/правого краю карти (без швів
      зшивання) — виконується на ОБОХ краях: захід — темна рамка
      сирця (медіани стовпця 0 = 7.6-10.9), схід — паддінг-рамка.
Суша ~29/144 (20.1%): материк + острів бази + архіпелаг.

Результат комітується константою GEO_LAYOUT у src/core/render-core.ts;
рантайм від ассета і цього скрипта НЕ залежить (розклад — константа).

Запуск: python3 scripts/geo-layout.py  (з кореня репо; залежність: Pillow)
"""

from PIL import Image
import numpy as np

SRC = 'assets-src/geo-map2.jpg'
WX0, WY0, CELL = 49, 158, 70  # вікно кропу; клітинка 70×70 (острів під (8,4))
TH = 17.0  # поріг за фактичним джерелом (див. docstring)
PAD_E, PAD_S = 145, 20  # безшовні паддінги ассета (схід/південь)

im = Image.open(SRC).convert('RGB')
a = np.asarray(im).astype(float)
lum = 0.2126 * a[:, :, 0] + 0.7152 * a[:, :, 1] + 0.0722 * a[:, :, 2]
H, W = lum.shape
win_h, win_w = 9 * CELL, 16 * CELL  # 630 x 1120 — ассет 1:1 з вікном

med = np.zeros((9, 16))
for gy in range(9):
    for gx in range(16):
        y1, x1 = WY0 + gy * CELL, WX0 + gx * CELL
        y2, x2 = min(y1 + CELL, H), min(x1 + CELL, W)  # за сирцем — паддінг (темна рамка)
        win = lum[y1:y2, x1:x2]
        # стовпці за межами сирця (схід) — паддінг ~9: медіана — океан
        med[gy, gx] = np.median(win) if win.size else 9.0

land = med > TH
base_med = med[4, 8]
edges_ok = not land[:, 0].any() and not land[:, 15].any()
frac = land.mean() * 100

rows = []
for gy in range(9):
    # (8,4) — B за призначенням (острів дрібніший за клітинку — фідбек «масштаб мельче»)
    rows.append(''.join('B' if (gx, gy) == (8, 4) else 'L' if land[gy, gx] else '.' for gx in range(16)))

print('джерело %dx%d, вікно x %d..%d(+%d паддінг), y %d..%d(+%d дзеркало), клітинка %d, поріг %.1f'
      % (W, H, WX0, min(WX0 + win_w, W), PAD_E, WY0, min(WY0 + win_h, H), PAD_S, CELL, TH))
print('медіана клітинки бази (8,4): %.2f (B за маркером — острів дрібніший за клітинку)' % base_med)
print(' суша: %d/144 (%.1f%%)' % (land.sum(), frac))
print(' (б) краї X — океан:       %s' % ('OK' if edges_ok else 'FAIL'))
print('GEO_LAYOUT:')
for r in rows:
    print("  '%s'," % r)
assert edges_ok, 'жорстка перевірка (б) не пройдено — стоп'
